func TestMergeExplodePreservesOverlappingFileRanks(t *testing.T) {
	// The short generated test must follow the longer non-generated test.
	// Skipped content loses its original bytes, but not its stored category.
	docs := []Document{
		{Name: "vendor/mock_test.go", Content: []byte("// Code generated by mockgen. DO NOT EDIT.\npackage mock")},
		{Name: "much_longer_handwritten_test.go", Content: []byte("package tests")},
		{Name: "skipped.go", Content: []byte("// Code generated by mockgen. DO NOT EDIT.\npackage mock"), SkipReason: SkipReasonTooManyTrigrams},
	}
	wantNames := []string{"much_longer_handwritten_test.go", "vendor/mock_test.go", "skipped.go"}
	wantCategories := []FileCategory{FileCategoryTest, FileCategoryTest, FileCategoryGenerated}
	check := func(d *indexData) {
		t.Helper()
		if got := len(d.fileBranchMasks); got != len(d.repoMetaData)*len(docs) {
			t.Fatalf("document count = %d", got)
		}
		for i := range d.fileBranchMasks {
			j := i % len(docs)
			if got := string(d.fileName(uint32(i))); got != wantNames[j] {
				t.Fatalf("document %d = %q, want %q", i, got, wantNames[j])
			}
			if got := d.getCategory(uint32(i)); got != wantCategories[j] {
				t.Fatalf("document %d category = %v, want %v", i, got, wantCategories[j])
			}
		}
	}
	var inputs []*indexData
	for _, name := range []string{"repo1", "repo2"} {
		b, err := NewBuilder(Options{
			IndexDir: t.TempDir(), DisableCTags: true,
			RepositoryDescription: zoekt.Repository{Name: name},
		})
		if err != nil {
			t.Fatal(err)
		}
		for _, doc := range docs {
			if err := b.Add(doc); err != nil {
				t.Fatal(err)
			}
		}
		if err := b.Finish(); err != nil {
			t.Fatal(err)
		}
		data, err := os.ReadFile(b.opts.shardName(0))
		if err != nil {
			t.Fatal(err)
		}
		s, err := NewSearcher(&memSeeker{data})
		if err != nil {
			t.Fatal(err)
		}
		defer s.Close()
		d := s.(*indexData)
		check(d)
		inputs = append(inputs, d)
	}
	sb, err := merge(inputs...)
	if err != nil {
		t.Fatal(err)
	}
	merged := searcherForTest(t, sb)
	defer merged.Close()
	check(merged.(*indexData))
	var buf bytes.Buffer
	if err := sb.Write(&buf); err != nil {
		t.Fatal(err)
	}
	exploded, err := explode(t.TempDir(), &memSeeker{buf.Bytes()})
	if err != nil {
		t.Fatal(err)
	}
	if len(exploded) != len(inputs) {
		t.Fatalf("exploded %d shards, want %d", len(exploded), len(inputs))
	}
	for path := range exploded {
		data, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		s, err := NewSearcher(&memSeeker{data})
		if err != nil {
			t.Fatal(err)
		}
		defer s.Close()
		check(s.(*indexData))
	}
}

func TestMergePreservesStoredCategoryForSkippedGeneratedFile(t *testing.T) {
	sb, err := NewShardBuilder(&zoekt.Repository{Name: "repo"})
	if err != nil {
		t.Fatalf("NewShardBuilder: %v", err)
	}

	err = sb.Add(Document{
		Name:       "generated.go",
		Content:    []byte("// Code generated by protoc-gen-go. DO NOT EDIT.\npackage generated\n"),
		SkipReason: SkipReasonTooManyTrigrams,
	})
	if err != nil {
		t.Fatalf("Add: %v", err)
	}

	tmpDir := t.TempDir()
	inputPath := filepath.Join(tmpDir, "input.zoekt")
	if err := builderWriteAll(inputPath, sb); err != nil {
		t.Fatalf("builderWriteAll: %v", err)
	}

	inputFile, err := os.Open(inputPath)
	if err != nil {
		t.Fatalf("Open: %v", err)
	}
	defer inputFile.Close()

	indexFile, err := NewIndexFile(inputFile)
	if err != nil {
		t.Fatalf("NewIndexFile: %v", err)
	}
	defer indexFile.Close()

	tmpName, dstName, err := Merge(tmpDir, indexFile)
	if err != nil {
		t.Fatalf("Merge: %v", err)
	}
	if err := os.Rename(tmpName, dstName); err != nil {
		t.Fatalf("Rename: %v", err)
	}

	mergedFile, err := os.Open(dstName)
	if err != nil {
		t.Fatalf("Open merged shard: %v", err)
	}
	defer mergedFile.Close()

	mergedIndexFile, err := NewIndexFile(mergedFile)
	if err != nil {
		t.Fatalf("NewIndexFile merged shard: %v", err)
	}
	defer mergedIndexFile.Close()

	searcher, err := NewSearcher(mergedIndexFile)
	if err != nil {
		t.Fatalf("NewSearcher: %v", err)
	}
	defer searcher.Close()

	data := searcher.(*indexData)
	if got := data.getCategory(0); got != FileCategoryGenerated {
		t.Fatalf("got category %v, want %v", got, FileCategoryGenerated)
	}
}

// We compare 2 simple shards before and after the transformation
// explode(merge(shard1, shard2)). We expect the input and output shards to be
// identical.
func TestExplode(t *testing.T) {
	simpleShards := []string{
		".././testdata/shards/repo_v16.00000.zoekt",
		".././testdata/shards/repo2_v16.00000.zoekt",
	}

	// repo name -> IndexMetadata
	m := make(map[string]*zoekt.IndexMetadata, 2)

	// merge
	var files []IndexFile
	for _, fn := range simpleShards {
		f, err := os.Open(fn)
		if err != nil {
			t.Fatal(err)
		}
		defer f.Close()

		indexFile, err := NewIndexFile(f)
		if err != nil {
			t.Fatal(err)
		}
		defer indexFile.Close()

		// We save indexMeta because the fields ID and IndexTime are the 2 sources of
		// non-determinism when building a new shard.
		repoMeta, indexMeta, err := ReadMetadata(indexFile)
		if err != nil {
			t.Fatal(err)
		}
		if len(repoMeta) != 1 {
			t.Fatal("this test assumes that indexFile contains only 1 repo")
		}
		m[repoMeta[0].Name] = indexMeta

		files = append(files, indexFile)
	}

	tmpDir := t.TempDir()
	tmpName, dstName, err := Merge(tmpDir, files...)
	if err != nil {
		t.Fatal(err)
	}
	err = os.Rename(tmpName, dstName)
	if err != nil {
		t.Fatal(err)
	}

	// explode
	f, err := os.Open(dstName)
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()

	indexFile, err := NewIndexFile(f)
	if err != nil {
		t.Fatal(err)
	}
	defer indexFile.Close()

	overwriteIndexTimeAndID := func(ib *ShardBuilder) {
		ib.ID = m[ib.repoList[0].Name].ID
		ib.IndexTime = m[ib.repoList[0].Name].IndexTime
	}
	exploded, err := explode(tmpDir, indexFile, overwriteIndexTimeAndID)
	if err != nil {
		t.Fatal(err)
	}
	for tmp, final := range exploded {
		err = os.Rename(tmp, final)
		if err != nil {
			t.Fatal(err)
		}
	}

	for _, s := range simpleShards {
		checkSameShards(t, s, filepath.Join(tmpDir, filepath.Base(s)))
	}
}

// TestExplodeEmptyShard verifies that exploding a compound shard with zero
// repositories removes the shard and returns success, instead of failing and
// leaving an unusable shard on disk. A compound shard reaches this state once
// all of its repos have been tombstoned and merged out. Such a shard cannot be
// loaded by zoekt-webserver, so leaving it in place drives up the indexed
// search error rate until it is removed.
func TestExplodeEmptyShard(t *testing.T) {
	dir := t.TempDir()

	// Build a compound shard that contains no repositories.
	sb := newShardBuilder(0)
	sb.indexFormatVersion = NextIndexFormatVersion
	path := filepath.Join(dir, fmt.Sprintf("compound-empty_v%d.00000.zoekt", NextIndexFormatVersion))
	if err := builderWriteAll(path, sb); err != nil {
		t.Fatalf("builderWriteAll: %v", err)
	}

	// Confirm the shard really is the empty-shard case.
	if _, _, err := ReadMetadataPath(path); !errors.Is(err, ErrEmptyShard) {
		t.Fatalf("ReadMetadataPath: got %v, want ErrEmptyShard", err)
	}

	// Explode should remove the empty shard and return nil.
	if err := Explode(dir, path); err != nil {
		t.Fatalf("Explode: %v", err)
	}
	if _, err := os.Stat(path); !os.IsNotExist(err) {
		t.Fatalf("empty shard was not removed, stat err = %v", err)
	}
}

// checkSameShards compares 2 shards byte by byte. The shards are expected to be
// small enough to be read in all at once.
func checkSameShards(t *testing.T, shard1, shard2 string) {
	t.Helper()
	b1, err := os.ReadFile(shard1)
	if err != nil {
		t.Fatal(err)
	}

	b2, err := os.ReadFile(shard2)
	if err != nil {
		t.Fatal(err)
	}

	// We could also use bytes.Equal, but the output of cmd.Diff is very helpful for
	// differences in metadata.
	d := cmp.Diff(b1, b2)
	if d == "" {
		return
	}

	if *update {
		t.Logf("updating %s", shard1)
		err := os.WriteFile(shard1, b2, 0o600)
		if err != nil {
			t.Fatal(err)
		}
		return
	}

	t.Fatalf("-%s\n+%s:\n%s", shard1, shard2, d)
}

// Merged documents carry no SkipReason, so merge and explode must copy each
// repository's skipped file counts from its source shard.
func TestMergeExplodePreservesSkippedFiles(t *testing.T) {
	inputDir, mergeDir := t.TempDir(), t.TempDir()
	branches := []zoekt.RepositoryBranch{{Name: "main"}, {Name: "dev"}}

	build := func(name string, docs ...Document) *os.File {
		sb, err := NewShardBuilder(&zoekt.Repository{Name: name, Branches: branches})
		if err != nil {
			t.Fatal(err)
		}
		for _, d := range docs {
			if err := sb.Add(d); err != nil {
				t.Fatal(err)
			}
		}
		fn := filepath.Join(inputDir, name+".zoekt")
		if err := builderWriteAll(fn, sb); err != nil {
			t.Fatal(err)
		}
		f, err := os.Open(fn)
		if err != nil {
			t.Fatal(err)
		}
		t.Cleanup(func() { f.Close() })
		return f
	}

	readSkipped := func(paths ...string) map[string]zoekt.SkippedFiles {
		got := map[string]zoekt.SkippedFiles{}
		for _, p := range paths {
			repos, _, err := ReadMetadataPath(p)
			if err != nil {
				t.Fatal(err)
			}
			for _, r := range repos {
				got[r.Name] = r.SkippedFiles
			}
		}
		return got
	}

	var inputs []IndexFile
	for _, f := range []*os.File{
		build("a",
			Document{Name: "large", SkipReason: SkipReasonTooLarge, Branches: []string{"main", "dev"}},
			Document{Name: "bin", Content: []byte("a\x00b"), Branches: []string{"dev"}},
			Document{Name: "text", Content: []byte("not skipped"), Branches: []string{"main"}}),
		build("b",
			Document{Name: "trigrams", SkipReason: SkipReasonTooManyTrigrams, Branches: []string{"main"}}),
	} {
		indexFile, err := NewIndexFile(f)
		if err != nil {
			t.Fatal(err)
		}
		defer indexFile.Close()
		inputs = append(inputs, indexFile)
	}

	want := map[string]zoekt.SkippedFiles{
		"a": {
			TooLarge: zoekt.SkippedFileCount{Total: 1, DefaultBranch: 1},
			Binary:   zoekt.SkippedFileCount{Total: 1, DefaultBranch: 0},
		},
		"b": {
			TooManyTrigrams: zoekt.SkippedFileCount{Total: 1, DefaultBranch: 1},
		},
	}

	tmpName, compound, err := Merge(mergeDir, inputs...)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.Rename(tmpName, compound); err != nil {
		t.Fatal(err)
	}
	if diff := cmp.Diff(want, readSkipped(compound)); diff != "" {
		t.Fatalf("merged mismatch (-want +got):\n%s", diff)
	}

	f, err := os.Open(compound)
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	indexFile, err := NewIndexFile(f)
	if err != nil {
		t.Fatal(err)
	}
	defer indexFile.Close()
	exploded, err := explode(mergeDir, indexFile)
	if err != nil {
		t.Fatal(err)
	}
	var paths []string
	for tmp, final := range exploded {
		if err := os.Rename(tmp, final); err != nil {
			t.Fatal(err)
		}
		paths = append(paths, final)
	}
	if diff := cmp.Diff(want, readSkipped(paths...)); diff != "" {
		t.Fatalf("exploded mismatch (-want +got):\n%s", diff)
	}
}
